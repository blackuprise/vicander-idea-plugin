package io.vicander.idea;

import com.intellij.codeInsight.navigation.actions.GotoDeclarationHandler;
import com.intellij.openapi.actionSystem.DataContext;
import com.intellij.openapi.editor.Editor;
import com.intellij.psi.PsiElement;
import com.intellij.psi.util.PsiTreeUtil;
import org.elixir_lang.psi.call.Call;
import org.elixir_lang.psi.qualification.Qualified;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * Ctrl+click on {@code fun} in {@code TodoListRepository.impl().fun(...)} goes to where the port
 * declares it.
 *
 * <p>{@code impl()} returns the adapter chosen by configuration at runtime, so the call has no
 * static target, and the port's callbacks are generated by {@code use DDD.Repository} /
 * {@code repo ... do find_by ... end} rather than written out. The port module is found from the
 * qualifier of {@code impl()} (resolved through {@code alias}). The base callbacks
 * ({@code find_by_id}, {@code save}, ...) go to the port's {@code use DDD.Repository}; a
 * {@code find_by_<field>[_and_<field>]} goes to the {@code find_by} that declares it.
 */
public final class RepositoryGotoDeclarationHandler implements GotoDeclarationHandler {
  private static final String USE = "use";
  private static final String FIND_BY = "find_by";
  private static final String PORT = "DDD.Repository";
  private static final String IMPL = "impl";
  private static final Pattern USE_PORT =
      Pattern.compile("\\s*" + Pattern.quote(PORT) + "\\s*(,[\\s\\S]*)?");
  private static final Pattern ALIAS = Pattern.compile("[A-Z]\\w*(\\.[A-Z]\\w*)*");

  /** Callbacks every port declares (see {@code DDD.Repository.__before_compile__}). */
  private static final Set<String> BASE_CALLBACKS =
      Set.of("find_by_id", "save", "delete", "list", "page", "slice", "count");

  @Override
  public PsiElement @Nullable [] getGotoDeclarationTargets(
      @Nullable PsiElement sourceElement, int offset, Editor editor) {
    if (sourceElement == null) {
      return null;
    }

    Call call = PsiTreeUtil.getParentOfType(sourceElement, Call.class, false);
    if (call == null
        || call.functionNameElement() == null
        || !PsiTreeUtil.isAncestor(call.functionNameElement(), sourceElement, false)
        || !(call instanceof Qualified)) {
      return null;
    }
    String functionName = call.functionName();
    if (functionName == null) {
      return null;
    }

    // The qualifier must be `Port.impl()`.
    PsiElement qualifier = ((Qualified) call).qualifier();
    if (!(qualifier instanceof Call)
        || !IMPL.equals(((Call) qualifier).functionName())
        || !(qualifier instanceof Qualified)) {
      return null;
    }
    PsiElement portAlias = ((Qualified) qualifier).qualifier();
    if (portAlias == null) {
      return null;
    }

    // Cheap exit: only the base callbacks and `find_by_*` finders are ever declared by a port.
    if (!BASE_CALLBACKS.contains(functionName) && !functionName.startsWith(FIND_BY + "_")) {
      return null;
    }

    Set<Call> ports = new LinkedHashSet<>();
    ModuleLookup.collectModules(portAlias, ports, 0);
    ModuleLookup.retainProjectModules(ports, call.getProject());

    List<PsiElement> targets = new ArrayList<>();
    for (Call port : ports) {
      for (Call inner : ModuleLookup.ownCalls(port)) {
        if (BASE_CALLBACKS.contains(functionName) && isUsePort(inner)) {
          add(targets, inner);
        } else if (FIND_BY.equals(inner.functionName()) && declaresFinder(inner, functionName)) {
          add(targets, inner);
        }
      }
    }
    return targets.isEmpty() ? null : targets.toArray(PsiElement.EMPTY_ARRAY);
  }

  private static void add(List<PsiElement> targets, Call call) {
    PsiElement name = call.functionNameElement();
    targets.add(name != null ? name : call);
  }

  /** {@code use DDD.Repository} (but not {@code use DDD.Repository.Ecto}). */
  private static boolean isUsePort(Call call) {
    if (!USE.equals(call.functionName())) {
      return false;
    }
    PsiElement[] arguments = call.primaryArguments();
    if (arguments == null || arguments.length == 0) {
      return false;
    }
    PsiElement first = arguments[0];
    // `use DDD.Repository` or `use DDD.Repository, opts` when parsed as a single argument.
    if (isPortText(first.getText())) {
      return true;
    }
    // `alias DDD.Repository` then `use Repository`: resolve the alias and check the module.
    if (!ALIAS.matcher(first.getText().trim()).matches()) {
      return false;
    }
    Set<Call> modules = new LinkedHashSet<>();
    ModuleLookup.collectModules(first, modules, 0);
    for (Call module : modules) {
      PsiElement[] name = module.primaryArguments();
      if (name != null && name.length > 0 && PORT.equals(name[0].getText().trim())) {
        return true;
      }
    }
    return false;
  }

  /** {@code DDD.Repository}, optionally followed by {@code , opts} in the same argument. */
  static boolean isPortText(String text) {
    return USE_PORT.matcher(text).matches();
  }

  /**
   * True when {@code find_by :a} / {@code find_by [:a, :b]} generates {@code functionName}:
   * the fields joined with {@code _and_}, prefixed with {@code find_by_}.
   */
  private static boolean declaresFinder(Call findBy, String functionName) {
    PsiElement[] arguments = findBy.primaryArguments();
    if (arguments == null || arguments.length == 0) {
      return false;
    }
    return functionName.equals(finderName(arguments[0].getText()));
  }

  /**
   * The function {@code find_by <fields>} generates, from the text of its first argument
   * ({@code :a}, {@code [:a, :b]}, {@code a:}, {@code :"a"}), or null if it names no fields.
   * Only the first argument names fields; the rest are options ({@code unique: true}, ...).
   */
  static @Nullable String finderName(String firstArgument) {
    String text = firstArgument.trim();
    if (text.startsWith("[") && text.endsWith("]")) {
      text = text.substring(1, text.length() - 1);
    }
    List<String> fields = new ArrayList<>();
    for (String part : text.split(",")) {
      String field = part.trim();
      // `:name`, `:"name"`, and the keyword form `name:`.
      if (field.startsWith(":")) {
        field = field.substring(1);
      } else if (field.endsWith(":")) {
        field = field.substring(0, field.length() - 1);
      }
      field = field.replace("\"", "").trim();
      if (field.isEmpty()) {
        return null;
      }
      fields.add(field);
    }
    return "find_by_" + String.join("_and_", fields);
  }

  @Override
  public @Nullable String getActionText(@NotNull DataContext context) {
    return null;
  }
}
